package com.ejercicios.funciones;

public class Calculadora {
	
static int restar(int num1, int num2) {
	return num1-num2;
}

static float restar(float num1, float num2) {
	return num1-num2;
}
	
static int sumar(int num1, int num2) {
	return num1+num2;
}

static float sumar(float num1, float num2) {
	return num1+num2;
}
	
	
static int multiplicar(int num1, int num2) {
	return num1*num2;
}

static float multiplicar(float num1, float num2) {
	return num1*num2;
}

static float dividir(float num1, float num2) {
	return num1/num2;
}

static int dividir(int num1, int num2) {
	return num1/num2;
}



}
